"""Pure Navigator projections of explicit ATT&CK software facts. No inferred group attribution."""

from __future__ import annotations

from typing import Any

from . import __version__
from .attack import catalog, technique
from .threat_library import Library


def software_techniques(lib: Library, software_ids: tuple[str, ...]) -> dict[str, list[str]]:
    """Technique to public software source names. Format-1 libraries have no software techniques."""
    sources: dict[str, list[str]] = {}
    for sid in sorted(set(software_ids)):
        software = lib.software.get(sid)
        if software is None:
            continue
        for tid in sorted(set(getattr(software, 'techniques', ()))):
            if technique(tid) is not None:
                sources.setdefault(tid, []).append(f'{sid} {software.name}')
    return sources


def software_navigator(lib: Library, software_id: str) -> dict[str, Any]:
    software = lib.software.get(software_id.strip().upper())
    if software is None:
        raise LookupError('No such software in the threat library')
    sources = software_techniques(lib, (software.id,))
    return {
        'name': f'{software.id} {software.name}: techniques (Insight)',
        'versions': {'attack': lib.attack_version, 'navigator': '5.0.0', 'layer': '4.5'},
        'domain': 'enterprise-attack',
        'description': 'TLP:CLEAR. Techniques explicitly used by this software in pinned MITRE ATT&CK. '
        'No actor attribution or local report counts.',
        'layout': {'layout': 'side', 'showID': True, 'showName': True, 'expandedSubtechniques': 'annotated'},
        'techniques': [
            {
                'techniqueID': tid,
                'score': 1,
                'enabled': True,
                'comment': f'ATT&CK software: {software.id} {software.name}',
            }
            for tid in sorted(sources)
            if tid in catalog().techniques
        ],
        'metadata': [
            {'name': 'TLP', 'value': 'TLP:CLEAR'},
            {'name': 'Source', 'value': software.url},
            {'name': 'ATT&CK', 'value': lib.notice},
            {'name': 'Generated by', 'value': f'Insight {__version__}'},
        ],
    }
